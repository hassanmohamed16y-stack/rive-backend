#!/usr/bin/env bash
# RIVÉ one-server setup (Ubuntu 22.04/24.04). Run as root:
#   curl -fsSL https://raw.githubusercontent.com/hassanmohamed16y-stack/rive-backend/main/deploy/setup.sh -o setup.sh && bash setup.sh
# Safe to run again: existing secrets in deploy/.env are kept.
set -euo pipefail

OWNER="hassanmohamed16y-stack"
BASE=/opt/rive
DEPLOY="$BASE/rive-backend/deploy"
ENV_FILE="$DEPLOY/.env"
TOKEN_FILE=/root/.rive-github-token

say()  { printf '\n\033[1;32m==> %s\033[0m\n' "$*"; }
warn() { printf '\n\033[1;33m!! %s\033[0m\n' "$*"; }
die()  { printf '\n\033[1;31mXX %s\033[0m\n' "$*"; exit 1; }
secret() { openssl rand -hex "${1:-32}"; }

[ "$(id -u)" -eq 0 ] || die "شغّل السكربت كـ root (اكتب: sudo -i  وبعدين شغّله تاني)"

say "1/7 تحديث السيرفر وتثبيت الأدوات"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq git curl openssl ufw ca-certificates fail2ban unattended-upgrades >/dev/null
systemctl enable --now fail2ban >/dev/null
if ! command -v docker >/dev/null 2>&1; then
  curl -fsSL https://get.docker.com | sh >/dev/null
fi
systemctl enable --now docker >/dev/null

say "2/7 الجدار الناري: فتح 22 و80 و443 بس"
ufw allow 22/tcp >/dev/null
ufw allow 80/tcp >/dev/null
ufw allow 443/tcp >/dev/null
ufw allow 443/udp >/dev/null
ufw --force enable >/dev/null

# Builds need memory; add 4 GB swap once if the server has none.
if ! swapon --show | grep -q .; then
  say "إضافة ذاكرة احتياطية (swap) 4GB"
  fallocate -l 4G /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
  grep -q '/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

say "3/7 تحميل الكود من GitHub"
mkdir -p "$BASE"
if [ ! -s "$TOKEN_FILE" ]; then
  echo "الأدمن والمتجر ريبوهات خاصة، فمحتاجين مفتاح قراءة من GitHub (Fine-grained token)."
  read -r -s -p "الصق الـ GitHub token هنا ثم Enter: " GH_TOKEN; echo
  [ -n "$GH_TOKEN" ] || die "مفيش token"
  umask 077; printf '%s' "$GH_TOKEN" > "$TOKEN_FILE"
fi
GH_TOKEN=$(cat "$TOKEN_FILE")
for REPO in rive-backend rive-admin rive-store; do
  URL="https://x-access-token:${GH_TOKEN}@github.com/${OWNER}/${REPO}.git"
  if [ -d "$BASE/$REPO/.git" ]; then
    git -C "$BASE/$REPO" remote set-url origin "$URL"
    git -C "$BASE/$REPO" pull -q --ff-only origin main
  else
    git clone -q --branch main "$URL" "$BASE/$REPO" || die "تعذر تحميل $REPO — اتأكد إن الـ token ليه صلاحية قراءة على الريبو ده"
  fi
done

say "4/7 الإعدادات والمفاتيح السرية"
ask() { # ask VAR "السؤال" [default] [required]
  local var=$1 q=$2 def=${3:-} req=${4:-no} val=""
  while :; do
    if [ -n "$def" ]; then read -r -p "$q [$def]: " val; val=${val:-$def}; else read -r -p "$q: " val; fi
    [ -n "$val" ] || [ "$req" != yes ] && break
    echo "   القيمة دي مطلوبة."
  done
  printf '%s=%s\n' "$var" "$val" >> "$ENV_FILE"
}
if [ ! -s "$ENV_FILE" ]; then
  umask 077
  ADMIN_PW="Rive-$(secret 9)"
  cat > "$ENV_FILE" <<EOF
# Generated by setup.sh on $(date -u +%F). Keep this file private; it is not in git.
POSTGRES_PASSWORD=$(secret 24)
JWT_SECRET=$(secret 32)
JWT_EXPIRATION=7d
INTERNAL_CRON_SECRET=$(secret 32)
TWO_FACTOR_ENCRYPTION_KEY=$(secret 32)
N8N_ENCRYPTION_KEY=$(secret 32)
RIVE_AGENT_WEBHOOK_SECRET=$(secret 32)
AGENT_SERVICE_TOKEN=$(secret 32)
AGENT_EVENTS_ENABLED=false
AGENT_EVENTS_TEST=false
ADMIN_INITIAL_PASSWORD=$ADMIN_PW
EOF
  echo "دلوقتي هسألك على بيانات الخدمات. انسخها من Vercel (مشروع rive-backend > Settings > Environment Variables)."
  echo "اللي مش معاك دلوقتي اضغط Enter وسيبه فاضي (إلا المطلوب)."
  ask DOMAIN "الدومين" "riveeg.com" yes
  ask ACME_EMAIL "إيميلك (لشهادات الأمان https)" "" yes
  ask PAYMOB_API_KEY "PAYMOB_API_KEY" "" yes
  ask PAYMOB_HMAC_SECRET "PAYMOB_HMAC_SECRET" "" yes
  ask PAYMOB_INTEGRATION_ID_CARD "PAYMOB_INTEGRATION_ID_CARD (رقم)" "" yes
  ask PAYMOB_PUBLIC_KEY "PAYMOB_PUBLIC_KEY"
  ask PAYMOB_IFRAME_ID "PAYMOB_IFRAME_ID"
  ask CLOUDINARY_CLOUD_NAME "CLOUDINARY_CLOUD_NAME" "" yes
  ask CLOUDINARY_API_KEY "CLOUDINARY_API_KEY" "" yes
  ask CLOUDINARY_API_SECRET "CLOUDINARY_API_SECRET" "" yes
  ask EMAIL_PROVIDER_API_KEY "EMAIL_PROVIDER_API_KEY (Resend)" "" yes
  ask EMAIL_FROM_ADDRESS "EMAIL_FROM_ADDRESS" "no-reply@riveeg.com" yes
  ask WHATSAPP_ACCESS_TOKEN "WHATSAPP_ACCESS_TOKEN"
  ask WHATSAPP_PHONE_NUMBER_ID "WHATSAPP_PHONE_NUMBER_ID"
  ask WHATSAPP_VERIFY_TOKEN "WHATSAPP_VERIFY_TOKEN"
  ask META_APP_SECRET "META_APP_SECRET"
  ask META_PAGE_ACCESS_TOKEN "META_PAGE_ACCESS_TOKEN"
  ask META_VERIFY_TOKEN "META_VERIFY_TOKEN"
  # Empty optional values must not be passed at all (the backend rejects empty META_* values).
  sed -i -E '/^[A-Z_]+=$/d' "$ENV_FILE"
  NEW_ENV=yes
else
  echo "ملف الإعدادات موجود، هستخدمه زي ما هو."
  NEW_ENV=no
fi
set -a; . "$ENV_FILE"; set +a

say "5/7 بناء البرامج (أول مرة بتاخد 10-20 دقيقة)"
cd "$DEPLOY"
mkdir -p backups
docker compose build --pull

say "6/7 تشغيل قاعدة البيانات وتجهيزها"
docker compose up -d postgres
docker compose run --rm --entrypoint sh backend -c "npx prisma migrate deploy && node scripts/seed.js"

say "7/7 تشغيل كل حاجة"
docker compose up -d
docker image prune -f >/dev/null

say "خلصنا!"
cat <<EOF

  المتجر:   https://$DOMAIN
  الأدمن:   https://admin.$DOMAIN
  الـ API:  https://api.$DOMAIN
  n8n:      https://n8n.$DOMAIN

  شهادات https بتطلع لوحدها أول ما الدومين يشاور على السيرفر (ممكن تاخد دقيقة أو اتنين).
EOF
if [ "$NEW_ENV" = yes ]; then
  cat <<EOF

  دخول الأدمن لأول مرة:
    الإيميل:      admin@rive.com
    كلمة السر:    $ADMIN_INITIAL_PASSWORD
  غيّرها من الإعدادات أول ما تدخل، واحفظها في مكان آمن.

  أول ما تفتح n8n هيطلب منك تعمل حساب صاحب السيرفر.
EOF
fi
